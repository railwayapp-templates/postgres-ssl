#!/usr/bin/env bash
# A crash between an append to postgresql.auto.conf and its writeback leaves
# NUL bytes where the line should be (seen in VM conformance guest_crash:
# "syntax error in file postgresql.auto.conf line 3, near token """).
# heal_nul_bytes must drop them and keep every real setting.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
source <(sed -n '/^heal_nul_bytes() {$/,/^}$/p' "$ROOT/wrapper.sh")
AUTO="$WORK/postgresql.auto.conf"

# A torn append: two real lines, then 22 NUL bytes where max_connections was.
printf "# Do not edit this file manually!\nwal_level = 'logical'\n" > "$AUTO"
head -c 22 /dev/zero >> "$AUTO"
heal_nul_bytes "$AUTO" | grep -q 'holds NUL bytes from a torn write'
[ "$(tr -d '\000' < "$AUTO" | cmp -s - "$AUTO"; echo $?)" = 0 ]
grep -q "wal_level = 'logical'" "$AUTO"
[ "$(wc -l < "$AUTO")" = 2 ]
! grep -q max_connections "$AUTO"   # the caller appends it again afterwards

# A clean file is left alone: same bytes, no log line.
cp "$AUTO" "$WORK/before"
[ -z "$(heal_nul_bytes "$AUTO")" ]
cmp -s "$AUTO" "$WORK/before"

# A missing file is not an error.
heal_nul_bytes "$WORK/absent"
echo 'heal_nul_bytes removes torn-append NUL bytes and keeps real settings'
